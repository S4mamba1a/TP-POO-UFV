CREATE TABLE PALHACO (
    id INT NOT NULL AUTO_INCREMENT,
    personalidade VARCHAR(45) NOT NULL,
    nota DOUBLE NOT NULL,
    cache DOUBLE NOT NULL,
    nome VARCHAR(45) NOT NULL,
    data_nascimento DATE NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE INSTRUMENTO_DE_RISADA (
    id INT NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL,
    descricao VARCHAR(300) NOT NULL,
    valor DOUBLE NOT NULL,
    PALHACO_id INT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_INSTRUMENTO_DE_RISADA_PALHACO
        FOREIGN KEY (PALHACO_id)
        REFERENCES PALHACO (id)
);

CREATE TABLE AVALIACAO (
    id INT NOT NULL AUTO_INCREMENT,
    valor INT NOT NULL,
    descricao VARCHAR(300) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE CONTRATANTE (
    id INT NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL,
    data_nascimento DATE NOT NULL,
    senha VARCHAR(45) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE CLIENTE (
    id INT NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL,
    data_nascimento DATE NOT NULL,
    descricao_fisica VARCHAR(100) NOT NULL,
    endereco VARCHAR(45) NOT NULL,
    local_de_trabalho VARCHAR(45) NOT NULL,
    CONTRATANTE_id INT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_CLIENTE_CONTRATANTE1
        FOREIGN KEY (CONTRATANTE_id)
        REFERENCES CONTRATANTE (id)
);

CREATE TABLE CONTRATO (
    id INT NOT NULL AUTO_INCREMENT,
    data_final DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    CONTRATANTE_id INT NOT NULL,
    CLIENTE_id INT NOT NULL,
    PALHACO_id INT NOT NULL,
    INSTRUMENTO_DE_RISADA_id INT NOT NULL,
    AVALIACAO_id INT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_CONTRATO_CONTRATANTE1
        FOREIGN KEY (CONTRATANTE_id)
        REFERENCES CONTRATANTE (id),
    CONSTRAINT fk_CONTRATO_CLIENTE1
        FOREIGN KEY (CLIENTE_id)
        REFERENCES CLIENTE (id),
    CONSTRAINT fk_CONTRATO_PALHACO1
        FOREIGN KEY (PALHACO_id)
        REFERENCES PALHACO (id),
    CONSTRAINT fk_CONTRATO_INSTRUMENTO_DE_RISADA1
        FOREIGN KEY (INSTRUMENTO_DE_RISADA_id)
        REFERENCES INSTRUMENTO_DE_RISADA (id),
    CONSTRAINT fk_CONTRATO_AVALIACAO1
        FOREIGN KEY (AVALIACAO_id)
        REFERENCES AVALIACAO (id)
);